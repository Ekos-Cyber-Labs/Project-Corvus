"""Frozen test-only oracle for free-text pseudonym replacement.

This module is a byte-for-byte copy of the committed per-entry
implementation from ``corvus/guardrails/pseudonymizer.py``
(``_replace_free_text`` plus every pure helper it needs), frozen at
the single-pass fix and renamed to ``legacy_replace_free_text``. It
is the differential-test oracle: the shipped implementation must
reproduce it byte for byte on every corpus input.

DO NOT EDIT this file to make a failing differential pass. If an
intended rule change diverges from it, name the rule, explain why,
and get maintainer approval first; then re-freeze from the new
committed implementation and record the reason here.

Only ``corvus.normalize.ocsf`` canonicalizers are imported (pinned
normalizer semantics shared with production); everything else the
loop needs is copied below so matcher changes in production fail
this oracle closed instead of silently following.
"""

from __future__ import annotations

import re
from collections.abc import Callable

from corvus.normalize.ocsf import (
    canonicalize_host,
    canonicalize_ip,
    canonicalize_user,
)

__all__ = ["legacy_replace_free_text"]

#: Token characters that forbid a free-text match on either side.
_TOKEN_CHARS = "A-Za-z0-9_.@-"

#: Token characters for REGISTERED values: ``_`` and ``-`` count as
#: separators (``svc_<user>_backup`` hides ``<user>``), so joined names
#: cannot smuggle a known entity past the model. Scanner-discovered
#: values keep the strict class above: the scanner never saw them as
#: entities, so a joined spelling stays untouched.
_REGISTERED_TOKEN_CHARS = "A-Za-z0-9.@"

#: Loose email shape check (full validation is not needed for lookup).
EMAIL_PATTERN = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")

#: A trailing multi-label domain suffix for short hostnames in free
#: text (``.example.com`` but not ``.exe``).
_HOST_SUFFIX = r"(?:\.[A-Za-z0-9-]+){2,}"

#: Sentence punctuation that may follow a name without belonging to
#: it: a run of ``.``, ``?`` or ``!`` (an ellipsis counts) followed
#: by the end of the text, whitespace, or a closing quote/bracket.
#: The run stays in the output after the pseudonym.
_SENTENCE_PUNCT = r"[.?!]+"

#: Closing characters that may end a sentence after the punctuation.
_CLOSING_CHARS = r")\]}'\""

#: Decimal literals below this length never match a registered IP:
#: short values (ports, counts, single octets) must not be eaten by
#: the decimal-IPv4 matcher.
_MIN_DECIMAL_IP_DIGITS = 7


def _token_bounds(text: str, start: int, end: int) -> tuple[int, int]:
    """Expand ``(start, end)`` to the whitespace-delimited token around it."""
    begin = start
    while begin > 0 and not text[begin - 1].isspace() and text[begin - 1] not in "\"'":
        begin -= 1
    stop = end
    while stop < len(text) and not text[stop].isspace() and text[stop] not in "\"'":
        stop += 1
    return begin, stop


def _is_path_component(text: str, start: int, end: int, kind: str) -> bool:
    """True when the span at ``(start, end)`` is a non-host path component.

    Host positions stay replaceable: a UNC first component
    (``\\\\HOST\\share``), a URL host (``https://HOST/path``) and a
    profile/home owner (``C:\\Users\\USER\\...``, ``/home/USER/...``).
    Every other component of a token holding a path separator is a
    file or directory name and is never an entity.
    """
    if kind in ("email", "ip"):
        return False
    begin, stop = _token_bounds(text, start, end)
    token = text[begin:stop]
    if "\\" not in token and "/" not in token:
        return False
    rel_start, rel_end = start - begin, end - begin
    if token[rel_end : rel_end + 2] in (":/", ":\\"):
        return False
    if "://" in token:
        host_start = token.index("://") + 3
        host_end = token.find("/", host_start)
        if host_end == -1:
            host_end = len(token)
        host_end = min(
            host_end,
            token.find(":", host_start) if ":" in token[host_start:] else host_end,
        )
        return not (rel_start >= host_start and rel_end <= host_end)
    if rel_start != rel_end and ("\\" in text[start:end] or "/" in text[start:end]):
        return False
    comps = [(m.start(), m.end(), m.group(0)) for m in re.finditer(r"[^\\/]+", token)]
    index = next(
        (i for i, (cs, ce, _) in enumerate(comps) if cs <= rel_start < ce),
        None,
    )
    if index is None:
        return False
    if (
        index > 0
        and kind == "user"
        and comps[index - 1][2].lower() in ("users", "home")
    ):
        return False
    if index == 0:
        prefix = token[: comps[0][0]]
        if prefix.endswith(("\\\\", "//")):
            return False
        return len(comps) > 1
    return True


def canonicalize_domain(value: str | None) -> str | None:
    """Lowercase and strip one trailing dot; placeholders return None."""
    text = (value or "").strip().lower().rstrip(".")
    if text.lower() in ("", "-", "n/a", "unknown"):
        return None
    if not text or any(char.isspace() for char in text):
        return None
    return text


def canonicalize_email(value: str | None) -> str | None:
    """Lowercase a whole address; anything not shaped like one is None."""
    text = (value or "").strip().lower()
    if text.lower() in ("", "-", "n/a", "unknown"):
        return None
    if EMAIL_PATTERN.match(text) is None:
        return None
    return text


_CANONICALIZE: dict[str, Callable[..., str | None]] = {
    "host": canonicalize_host,
    "user": canonicalize_user,
    "ip": canonicalize_ip,
    "domain": canonicalize_domain,
    "email": canonicalize_email,
}


def _canonical(kind: str, raw: str) -> str | None:
    if kind == "ip":
        return canonicalize_ip_text(raw)
    return _CANONICALIZE[kind](raw)


def canonicalize_ip_text(value: str | None) -> str | None:
    """Canonicalize an IP, accepting non-canonical IPv4 spellings.

    Zero-padded octets (``010.070.001.020``), spaced dots
    (``10 . 70 . 1 . 20``) and 32-bit hex (``0x0A460114``) all resolve
    to the same canonical dotted quad, so every spelling maps to one
    pseudonym. Anything else delegates to
    :func:`corvus.normalize.ocsf.canonicalize_ip` unchanged (IPv6
    included).
    """
    text = (value or "").strip()
    if not text:
        return None
    lowered = text.lower()
    if re.fullmatch(r"0x[0-9a-f]{8}", lowered) is not None:
        try:
            packed = int(lowered, 16)
        except ValueError:
            return None
        dotted = ".".join(str((packed >> shift) & 0xFF) for shift in (24, 16, 8, 0))
        return canonicalize_ip(dotted)
    squashed = re.sub(r"\s*\.\s*", ".", text)
    parts = squashed.split(".")
    if len(parts) == 4 and all(part.isdigit() for part in parts):
        try:
            squashed = ".".join(str(int(part)) for part in parts)
        except ValueError:
            return None
    return canonicalize_ip(squashed)


def _ip_numbers(canonical: str) -> list[int] | None:
    """Split a canonical dotted quad into its four octets, else None."""
    parts = canonical.split(".")
    if len(parts) != 4 or any(not part.isdigit() for part in parts):
        return None
    try:
        numbers = [int(part) for part in parts]
    except ValueError:
        return None
    if any(number > 255 for number in numbers):
        return None
    return numbers


def _ip_match_body(canonical: str) -> str | None:
    """Match every IPv4 spelling of a canonical dotted quad, else None.

    One alternative covers the dotted form with optional leading zeros
    and optional spaces around the dots; the other covers the 8-digit
    hex form in either case. Non-quad canonicals (IPv6) return None
    and keep their exact matcher.
    """
    numbers = _ip_numbers(canonical)
    if numbers is None:
        return None
    octets = [("0+" if number == 0 else f"0*{number}") for number in numbers]
    dotted = r"\s*\.\s*".join(octets)
    packed = (numbers[0] << 24) | (numbers[1] << 16) | (numbers[2] << 8) | numbers[3]
    hexed = "".join(
        f"[{digit}{digit.lower()}]" if digit.isalpha() else digit
        for digit in f"{packed:08X}"
    )
    return f"(?:{dotted}|0[xX]{hexed})"


def _ip_packed(canonical: str) -> int | None:
    """Pack a canonical dotted quad into its 32-bit integer, else None."""
    numbers = _ip_numbers(canonical)
    if numbers is None:
        return None
    return (numbers[0] << 24) | (numbers[1] << 16) | (numbers[2] << 8) | numbers[3]


def _encoded_char_pattern(char: str) -> str:
    """Match ``char`` literally or as UTF-8 percent-escapes.

    ``@`` matches ``@`` and ``%40`` (either case), so
    ``user%40domain.example`` matches the registered
    ``user@domain.example`` and is replaced in its original spelling.
    """
    if char == "%":
        return "(?:%|%25)"
    encoded = ["%"]
    for byte in char.encode("utf-8"):
        for digit in f"{byte:02X}":
            encoded.append(f"[{digit}{digit.lower()}]" if digit.isalpha() else digit)
    return f"(?:{re.escape(char)}|{''.join(encoded)})"


def legacy_replace_free_text(
    text: str,
    table: dict[str, tuple[str, str]],
    registered: frozenset[tuple[str, str]] = frozenset(),
    emitted: set[str] | None = None,
) -> str:
    """Frozen copy of the committed per-entry free-text replacement.

    Replace known raw values inside one free-text string.

    Percent-escapes decode for matching (``%40`` matches ``@``) and
    the original spelling is what gets replaced. Registered values
    additionally treat ``_`` and ``-`` as separators. IPv4 entries
    match every spelling of their canonical quad (padded, spaced,
    hex). When ``emitted`` is given, every pseudonym actually
    substituted into the returned text is added to it (a text that
    already held a pseudonym-shaped token without any substitution
    adds nothing).
    """
    if not text or not table:
        return text
    for raw in sorted(table, key=len, reverse=True):
        pseudonym, kind = table[raw]
        if not raw or raw == pseudonym:
            continue
        flags = 0 if kind == "ip" else re.IGNORECASE
        token_chars = _TOKEN_CHARS
        if kind == "ip":
            variant = _ip_match_body(raw)
            if variant is not None:
                body = variant
            else:
                body = "".join(_encoded_char_pattern(char) for char in raw)
        else:
            entry_canonical = _canonical(kind, raw)
            if entry_canonical is not None and (kind, entry_canonical) in registered:
                token_chars = _REGISTERED_TOKEN_CHARS
            body = "".join(_encoded_char_pattern(char) for char in raw)
        if kind == "host" and "." not in raw:
            # Longest-first ordering already prefers an earlier full
            # spelling; the alternation tries the suffixed form first.
            body = f"(?:{body}{_HOST_SUFFIX}|{body})"
        pattern = re.compile(
            r"(?<!["
            + token_chars
            + r"])"
            + body
            + r"(?:(?P<punct>"
            + _SENTENCE_PUNCT
            + r")(?=$|\s|["
            + _CLOSING_CHARS
            + r"])|(?!["
            + token_chars
            + r"]))",
            flags,
        )

        def _emit(
            match: re.Match[str],
            pseudo: str = pseudonym,
            kind: str = kind,
            source: str = text,
        ) -> str:
            punct = match.group("punct") or ""
            core_end = match.end() - len(punct)
            if _is_path_component(source, match.start(), core_end, kind):
                return match.group(0)
            return pseudo + punct

        before = text
        text = pattern.sub(_emit, text)
        if text != before and emitted is not None:
            emitted.add(pseudonym)
        if kind == "ip":
            # Decimal-integer IPv4 (``src=173343012``): the packed
            # 32-bit value of a registered quad maps to the same
            # pseudonym. Short literals stay untouched (ports, counts).
            entry_canonical = _canonical(kind, raw)
            packed = (
                _ip_packed(entry_canonical) if entry_canonical is not None else None
            )
            if packed is not None and len(str(packed)) >= _MIN_DECIMAL_IP_DIGITS:
                before_int = text
                text = re.sub(rf"(?<!\d){packed}(?!\d)", pseudonym, text)
                if text != before_int and emitted is not None:
                    emitted.add(pseudonym)
    return text
